import assert from 'node:assert/strict';
import { packFrame } from '../web/src/packs/artFrames.js';
import { Animator, SpriteRenderer, drawTree } from '../web/src/engine/components.js';
import { GameObject } from '../web/src/engine/scene.js';
const frames = { Idle: ['idle'], Attack: ['attack1','attack2'], Skill_02: ['skill1','skill2'], Skill_02_01: ['dash1'] };
const pick = (sprite, clip, exists = () => true) => packFrame(sprite, clip, 'Hero_13', frames, 'still', exists);
assert.equal(pick('Hero_13_Attack_2','Hero_13_Skill_02'),'skill2');
assert.equal(pick('Hero_13_Attack_2','Hero_13_Attack'),'attack2');
assert.equal(pick('Hero_13_Attack_1','Hero_13_Skill_02_01'),'dash1');
assert.equal(pick('Hero_13_Skill_02_01_1',null),'dash1');
assert.equal(pick('Hero_13_Attack2',null),'attack2');
assert.equal(pick('Hero_13_Attack_2','Hero_13_Attack',n=>n!=='attack2'),'idle');
assert.equal(pick('Fx_Hero_13_Attack_1','Hero_13_Attack'),null);
assert.equal(pick('Hero_13_Die_1','Hero_13_Die'),'idle');
console.log('8 pack-frame checks passed: shared sprites, clip overrides, nested states, missing files, effects.');
const go = new GameObject('body');
const sr = go.add(new SpriteRenderer());
const clip = {length:1,sprites:[{pathHash:0,frames:[[0,'Hero_13_Attack_1'],[.5,'Hero_13_Attack_2']]}],events:[{t:.5,fn:'OnAttackEvent'}]};
const assets = {anims:{Hero_13_Skill_02:clip},sprite:n=>({name:n})};
const animator = go.add(new Animator(assets,{states:{Attack:{clip:'Hero_13_Attack'}}}));
animator.overrides.Hero_13_Attack='Hero_13_Skill_02';
animator.play('Attack',0);
let hits=0;animator.listeners.push(()=>hits++);animator.update(.5);
assert.equal(sr.animationClip,'Hero_13_Skill_02');assert.equal(sr.sprite,'Hero_13_Attack_2');assert.equal(hits,1);
go.spriteRemap=(base,activeClip)=>pick(base,activeClip);
let drawn;drawTree({draw:item=>drawn=item.sp.name},assets,go);
assert.equal(drawn,'skill2');
console.log('Animator override -> SpriteRenderer -> drawTree integration passed; impact event unchanged.');
